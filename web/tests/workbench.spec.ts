import { expect, test } from '@playwright/test'

test('fixture repair preserves both outcomes, proof, feedback and export', async ({ page, request }) => {
  const before = await (await request.get('/api/health')).json()
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: /Run verification/ }).click()
  await expect(page.getByRole('heading', { name: 'Change accepted', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Attempt 1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Attempt 1', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Change rejected', exact: true })).toBeVisible()
  await expect(page.locator('.failed-row').first()).toBeVisible()
  await page.getByRole('tab', { name: 'Revision feedback' }).click()
  await expect(page.locator('.feedback-view pre')).toContainText('counterexamples')
  await page.getByRole('button', { name: 'Attempt 2', exact: true }).click()
  await page.getByRole('tab', { name: 'Symbolic proof' }).click()
  await expect(page.locator('.proof-output')).toContainText('verdict: proved')
  await expect(page.locator('.proof-leaf.folded').first()).toBeVisible()
  await page.getByRole('tab', { name: 'Verified source' }).click()
  await expect(page.locator('.source-view pre')).toContainText('Append-Contents')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Export evidence' }).click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toMatch(/^iaca-.*\.json$/)
  await page.getByRole('button', { name: /Run history/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.locator('.history-item').first()).toContainText('Deterministic fixture')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  const after = await (await request.get('/api/health')).json()
  expect(after.live_calls_used).toBe(before.live_calls_used)
  expect(errors).toEqual([])
})

test('a zero-budget proof stays unresolved even when every execution test passes', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Fixture scenario').selectOption('unresolved')
  await page.getByRole('button', { name: /Run verification/ }).click()
  await expect(page.getByRole('heading', { name: 'Proof unresolved', exact: true })).toBeVisible()
  await expect(page.locator('.test-summary')).toContainText('216 of 216 passed')
  await page.getByRole('tab', { name: 'Symbolic proof' }).click()
  await expect(page.locator('.proof-output')).toContainText('incomplete')
  await expect(page.locator('.proof-output')).toContainText('0 / 0 STEPS')
})

test('manual injection is rejected before execution and a second task can run', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Your candidate' }).click()
  await page.getByLabel('Candidate expression').fill('<System \'not allowed\'>')
  await page.getByRole('button', { name: /Run verification/ }).click()
  await expect(page.getByRole('heading', { name: 'Change rejected', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Execution was not reached' })).toBeVisible()
  await page.getByLabel('Choose a task').selectOption('append_identity')
  await page.getByLabel('Candidate expression').fill('(e.A)')
  await page.getByRole('button', { name: /Run verification/ }).click()
  await expect(page.getByRole('heading', { name: 'Change accepted', exact: true })).toBeVisible()
  await expect(page.locator('.test-summary')).toContainText('6 of 6 passed')
})

test('mobile layout stays usable without horizontal page overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Code proposes. Evidence decides.' })).toBeVisible()
  await page.getByRole('button', { name: /Run verification/ }).click()
  await expect(page.getByRole('heading', { name: 'Change accepted', exact: true })).toBeVisible()
  const dimensions = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }))
  expect(dimensions.scroll).toBe(dimensions.width)
})
